export function mapDbProduct(row: any): Product {
  const inStock = Boolean(
    row.in_stock && (row.stock_qty === undefined || row.stock_qty === null || row.stock_qty > 0)
  );

  return {
    id: Number(row.id),
    slug: row.slug,
    cat: row.cat as ProductCategory,
    name: row.name,
    metal: row.metal as MetalType,
    pearl: row.pearl as PearlType,
    price: Number(row.price),
    was: row.was ? Number(row.was) : null,
    description: row.description || "",
    badge: row.badge || null,
    rating: Number(row.rating) || 5,
    in_stock: inStock,
    stock_qty: row.stock_qty !== undefined ? Number(row.stock_qty) : inStock ? 1 : 0,
    photos: Array.isArray(row.photos) ? row.photos : [],
    sort_order: Number(row.sort_order) || 0,
    created_at: row.created_at,
    updated_at: row.updated_at,
  };
}

export async function getProducts(): Promise<Product[]> {
  try {
    const { data, error } = await supabase
      .from("products")
      .select("*")
      .order("sort_order", { ascending: true });

    if (error || !data || data.length === 0) {
      console.warn("Using fallback initial products, Supabase query returned:", error);
      return INITIAL_PRODUCTS;
    }

    return data.map(mapDbProduct);
  } catch (err) {
    console.error("Failed to fetch products from Supabase:", err);
    return INITIAL_PRODUCTS;
  }
}

export async function getProductBySlug(slug: string): Promise<Product | null> {
  try {
    const { data, error } = await supabase
      .from("products")
      .select("*")
      .eq("slug", slug)
      .maybeSingle();

    if (error || !data) {
      const fallback = INITIAL_PRODUCTS.find((p) => p.slug === slug);
      return fallback || null;
    }

    return mapDbProduct(data);
  } catch (err) {
    console.error("Error retrieving product by slug:", err);
    const fallback = INITIAL_PRODUCTS.find((p) => p.slug === slug);
    return fallback || null;
  }
}

export function formatMoney(n: number): string {
  return "$" + n.toLocaleString("en-US", { maximumFractionDigits: 0 });
}
